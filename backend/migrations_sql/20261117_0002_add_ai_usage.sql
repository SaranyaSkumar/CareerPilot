-- CareerPilot AI usage ledger.
-- Apply once in the Supabase SQL editor (project kcrtedhezyovfygfotia).
-- This script only adds ai_usage_events. It does not drop or alter CV, profile, or job rows.
-- The API role careerpilot_app cannot CREATE, so startup does not apply this file.
-- The backend must filter by user_id itself: careerpilot_app has BYPASSRLS.

CREATE TABLE ai_usage_events (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL,
    operation character varying(40) NOT NULL,
    model character varying(120) NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'reserved',
    input_tokens integer NOT NULL DEFAULT 0,
    output_tokens integer NOT NULL DEFAULT 0,
    estimated_cost_usd numeric(12, 6) NOT NULL,
    actual_cost_usd numeric(12, 6),
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX ai_usage_events_user_created_idx ON ai_usage_events (user_id, created_at);
CREATE INDEX ai_usage_events_created_idx ON ai_usage_events (created_at);

ALTER TABLE ai_usage_events ENABLE ROW LEVEL SECURITY;

-- Owner policy for the authenticated role (Supabase Data API).
-- auth.uid() is wrapped in a scalar subquery so Postgres can cache it per statement.
-- The backend role careerpilot_app has BYPASSRLS and keeps a permissive policy,
-- so this policy does not constrain the API.
DO $$
BEGIN
    IF to_regprocedure('auth.uid()') IS NOT NULL
       AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        CREATE POLICY ai_usage_events_owner ON ai_usage_events
            FOR ALL TO authenticated
            USING ((SELECT auth.uid()) = user_id)
            WITH CHECK ((SELECT auth.uid()) = user_id);
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'careerpilot_app') THEN
        CREATE POLICY careerpilot_app_all ON ai_usage_events
            FOR ALL TO careerpilot_app USING (true) WITH CHECK (true);
    END IF;
END $$;

REVOKE ALL ON TABLE ai_usage_events FROM PUBLIC;
REVOKE ALL ON SEQUENCE ai_usage_events_id_seq FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        EXECUTE 'REVOKE ALL ON TABLE ai_usage_events FROM anon';
        EXECUTE 'REVOKE ALL ON SEQUENCE ai_usage_events_id_seq FROM anon';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE ai_usage_events TO authenticated';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE ai_usage_events_id_seq TO authenticated';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
        EXECUTE 'GRANT ALL ON TABLE ai_usage_events TO service_role';
        EXECUTE 'GRANT ALL ON SEQUENCE ai_usage_events_id_seq TO service_role';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'careerpilot_app') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE ai_usage_events TO careerpilot_app';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE ai_usage_events_id_seq TO careerpilot_app';
    END IF;
END $$;
