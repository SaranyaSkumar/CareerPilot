-- CareerPilot named CV variants.
-- Apply once in the Supabase SQL editor (project kcrtedhezyovfygfotia).
-- This script only adds cv_variants. It does not drop or alter existing rows.
-- The API role careerpilot_app cannot CREATE, so startup does not apply this file.
-- The backend must filter by user_id itself: careerpilot_app has BYPASSRLS.

CREATE TABLE cv_variants (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL,
    label character varying(160) NOT NULL,
    job_title character varying(200) NOT NULL DEFAULT '',
    company character varying(200) NOT NULL DEFAULT '',
    job_id integer,
    job_description text NOT NULL DEFAULT '',
    is_default boolean NOT NULL DEFAULT false,
    name character varying(160) NOT NULL DEFAULT '',
    headline character varying(200) NOT NULL DEFAULT '',
    summary text NOT NULL DEFAULT '',
    experience text NOT NULL DEFAULT '',
    skills text NOT NULL DEFAULT '',
    education text NOT NULL DEFAULT '',
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX cv_variants_user_created_idx ON cv_variants (user_id, created_at);
CREATE UNIQUE INDEX cv_variants_one_default_per_user ON cv_variants (user_id) WHERE is_default;

ALTER TABLE cv_variants ENABLE ROW LEVEL SECURITY;

-- Owner policy for the authenticated role (Supabase Data API).
-- auth.uid() is wrapped in a scalar subquery so Postgres can cache it per statement.
-- The backend role careerpilot_app has BYPASSRLS and keeps a permissive policy,
-- so this policy does not constrain the API.
DO $$
BEGIN
    IF to_regprocedure('auth.uid()') IS NOT NULL
       AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        CREATE POLICY cv_variants_owner ON cv_variants
            FOR ALL TO authenticated
            USING ((SELECT auth.uid()) = user_id)
            WITH CHECK ((SELECT auth.uid()) = user_id);
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'careerpilot_app') THEN
        CREATE POLICY careerpilot_app_all ON cv_variants
            FOR ALL TO careerpilot_app USING (true) WITH CHECK (true);
    END IF;
END $$;

REVOKE ALL ON TABLE cv_variants FROM PUBLIC;
REVOKE ALL ON SEQUENCE cv_variants_id_seq FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        EXECUTE 'REVOKE ALL ON TABLE cv_variants FROM anon';
        EXECUTE 'REVOKE ALL ON SEQUENCE cv_variants_id_seq FROM anon';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE cv_variants TO authenticated';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE cv_variants_id_seq TO authenticated';
        EXECUTE 'REVOKE TRUNCATE, REFERENCES, TRIGGER ON TABLE cv_variants FROM authenticated';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
        EXECUTE 'GRANT ALL ON TABLE cv_variants TO service_role';
        EXECUTE 'GRANT ALL ON SEQUENCE cv_variants_id_seq TO service_role';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'careerpilot_app') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE cv_variants TO careerpilot_app';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE cv_variants_id_seq TO careerpilot_app';
    END IF;
END $$;
