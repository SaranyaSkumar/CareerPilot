-- Independent career tracks; all existing CV and variant records are preserved.
CREATE TABLE career_track_profiles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL,
    name varchar(120) NOT NULL,
    employment_type varchar(20) NOT NULL DEFAULT 'full_time'
        CHECK (employment_type IN ('full_time','part_time','contract','casual','custom')),
    target_roles varchar(1000) NOT NULL DEFAULT '',
    location varchar(200) NOT NULL DEFAULT 'New Zealand',
    cv_name varchar(160) NOT NULL DEFAULT '',
    headline varchar(200) NOT NULL DEFAULT '',
    summary text NOT NULL DEFAULT '',
    experience text NOT NULL DEFAULT '',
    skills text NOT NULL DEFAULT '',
    education text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX career_track_profiles_user_updated_idx ON career_track_profiles(user_id, updated_at DESC);
ALTER TABLE career_track_profiles ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
    IF to_regprocedure('auth.uid()') IS NOT NULL
       AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        CREATE POLICY career_track_profiles_owner ON career_track_profiles
            FOR ALL TO authenticated
            USING ((SELECT auth.uid()) = user_id)
            WITH CHECK ((SELECT auth.uid()) = user_id);
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'careerpilot_app') THEN
        CREATE POLICY careerpilot_app_all ON career_track_profiles
            FOR ALL TO careerpilot_app USING (true) WITH CHECK (true);
    END IF;
END $$;
REVOKE ALL ON TABLE career_track_profiles FROM PUBLIC;
REVOKE ALL ON SEQUENCE career_track_profiles_id_seq FROM PUBLIC;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        EXECUTE 'REVOKE ALL ON TABLE career_track_profiles FROM anon';
        EXECUTE 'REVOKE ALL ON SEQUENCE career_track_profiles_id_seq FROM anon';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE career_track_profiles TO authenticated';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE career_track_profiles_id_seq TO authenticated';
        EXECUTE 'REVOKE TRUNCATE, REFERENCES, TRIGGER ON TABLE career_track_profiles FROM authenticated';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
        EXECUTE 'GRANT ALL ON TABLE career_track_profiles TO service_role';
        EXECUTE 'GRANT ALL ON SEQUENCE career_track_profiles_id_seq TO service_role';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'careerpilot_app') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE career_track_profiles TO careerpilot_app';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE career_track_profiles_id_seq TO careerpilot_app';
    END IF;
END $$;
ALTER TABLE cv_variants ADD COLUMN profile_id integer
    REFERENCES career_track_profiles(id) ON DELETE SET NULL;
CREATE INDEX cv_variants_profile_idx ON cv_variants(user_id, profile_id, updated_at DESC);
