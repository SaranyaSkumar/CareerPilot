-- User-scoped application tracker. The API enforces ownership using verified Supabase user IDs.
CREATE TABLE job_applications (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL,
    title character varying(200) NOT NULL,
    company character varying(200) NOT NULL DEFAULT '',
    location character varying(200) NOT NULL DEFAULT 'New Zealand',
    url character varying(2000) NOT NULL DEFAULT '',
    stage character varying(32) NOT NULL DEFAULT 'interested',
    applied_at date,
    next_action character varying(500) NOT NULL DEFAULT '',
    next_action_date date,
    notes text NOT NULL DEFAULT '',
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT job_applications_stage_check CHECK (
        stage IN ('interested', 'preparing', 'ready_to_apply', 'applied',
                  'assessment', 'interview', 'offer', 'rejected', 'withdrawn')
    )
);
CREATE INDEX job_applications_user_id_idx ON job_applications (user_id);
CREATE INDEX job_applications_stage_idx ON job_applications (stage);
CREATE INDEX job_applications_user_updated_idx ON job_applications (user_id, updated_at DESC);
ALTER TABLE job_applications ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
    IF to_regprocedure('auth.uid()') IS NOT NULL
       AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        CREATE POLICY job_applications_owner ON job_applications
            FOR ALL TO authenticated
            USING ((SELECT auth.uid()) = user_id)
            WITH CHECK ((SELECT auth.uid()) = user_id);
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'careerpilot_app') THEN
        CREATE POLICY careerpilot_app_all ON job_applications
            FOR ALL TO careerpilot_app USING (true) WITH CHECK (true);
    END IF;
END $$;
REVOKE ALL ON TABLE job_applications FROM PUBLIC;
REVOKE ALL ON SEQUENCE job_applications_id_seq FROM PUBLIC;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        EXECUTE 'REVOKE ALL ON TABLE job_applications FROM anon';
        EXECUTE 'REVOKE ALL ON SEQUENCE job_applications_id_seq FROM anon';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE job_applications TO authenticated';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE job_applications_id_seq TO authenticated';
        EXECUTE 'REVOKE TRUNCATE, REFERENCES, TRIGGER ON TABLE job_applications FROM authenticated';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'careerpilot_app') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE job_applications TO careerpilot_app';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE job_applications_id_seq TO careerpilot_app';
    END IF;
END $$;
