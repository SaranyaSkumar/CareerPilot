-- CareerPilot job discovery.
-- Apply once in the Supabase SQL editor (project kcrtedhezyovfygfotia).
-- This script adds discovery settings and provider bookkeeping.
-- It does not drop or rewrite profile, CV, AI usage, or existing job rows.
-- The API role careerpilot_app cannot CREATE, so startup does not apply this file.
-- The backend must filter user-owned rows by user_id itself: careerpilot_app has BYPASSRLS.
--
-- job_provider_cache and job_provider_quota hold public listing caches and
-- app-level request counters. They have no user_id. Row level security is on,
-- and authenticated and anon receive no privileges on them.

ALTER TABLE job_listings ADD COLUMN IF NOT EXISTS salary character varying(200) NOT NULL DEFAULT '';
ALTER TABLE job_listings ADD COLUMN IF NOT EXISTS posted_at timestamp with time zone;
ALTER TABLE job_listings ADD COLUMN IF NOT EXISTS dedupe_key character varying(400) NOT NULL DEFAULT '';

CREATE UNIQUE INDEX IF NOT EXISTS job_listings_user_dedupe_unique
    ON job_listings (user_id, dedupe_key) WHERE dedupe_key <> '';

CREATE TABLE job_discovery_settings (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL UNIQUE,
    country character varying(2) NOT NULL DEFAULT 'nz',
    location character varying(200) NOT NULL DEFAULT 'New Zealand',
    keywords character varying(300) NOT NULL DEFAULT '',
    remote_preference character varying(20) NOT NULL DEFAULT 'any',
    query_fingerprint character varying(64) NOT NULL DEFAULT '',
    last_discovered_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT job_discovery_settings_remote_check
        CHECK (remote_preference IN ('any', 'remote', 'onsite')),
    CONSTRAINT job_discovery_settings_country_check
        CHECK (country ~ '^[a-z]{2}$')
);

CREATE TABLE job_provider_settings (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL,
    provider_key character varying(40) NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT job_provider_settings_user_provider_unique UNIQUE (user_id, provider_key)
);

CREATE INDEX job_provider_settings_user_id_idx ON job_provider_settings (user_id);

CREATE TABLE job_provider_cache (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_key character varying(40) NOT NULL,
    query_fingerprint character varying(64) NOT NULL,
    payload json NOT NULL,
    fetched_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT job_provider_cache_query_unique UNIQUE (provider_key, query_fingerprint)
);

CREATE TABLE job_provider_quota (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_key character varying(40) NOT NULL,
    quota_day date NOT NULL,
    request_count integer NOT NULL DEFAULT 0,
    CONSTRAINT job_provider_quota_day_unique UNIQUE (provider_key, quota_day)
);

ALTER TABLE job_discovery_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE job_provider_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE job_provider_cache ENABLE ROW LEVEL SECURITY;
ALTER TABLE job_provider_quota ENABLE ROW LEVEL SECURITY;

-- Owner policies for the authenticated role (Supabase Data API).
-- auth.uid() is wrapped in a scalar subquery so Postgres can cache it per statement.
-- The backend role careerpilot_app has BYPASSRLS and keeps a permissive policy,
-- so these policies do not constrain the API.
-- Cache and quota tables have no owner policy: they are not user data.
DO $$
BEGIN
    IF to_regprocedure('auth.uid()') IS NOT NULL
       AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        CREATE POLICY job_discovery_settings_owner ON job_discovery_settings
            FOR ALL TO authenticated
            USING ((SELECT auth.uid()) = user_id)
            WITH CHECK ((SELECT auth.uid()) = user_id);
        CREATE POLICY job_provider_settings_owner ON job_provider_settings
            FOR ALL TO authenticated
            USING ((SELECT auth.uid()) = user_id)
            WITH CHECK ((SELECT auth.uid()) = user_id);
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'careerpilot_app') THEN
        CREATE POLICY careerpilot_app_all ON job_discovery_settings
            FOR ALL TO careerpilot_app USING (true) WITH CHECK (true);
        CREATE POLICY careerpilot_app_all ON job_provider_settings
            FOR ALL TO careerpilot_app USING (true) WITH CHECK (true);
        CREATE POLICY careerpilot_app_all ON job_provider_cache
            FOR ALL TO careerpilot_app USING (true) WITH CHECK (true);
        CREATE POLICY careerpilot_app_all ON job_provider_quota
            FOR ALL TO careerpilot_app USING (true) WITH CHECK (true);
    END IF;
END $$;

REVOKE ALL ON TABLE
    job_discovery_settings,
    job_provider_settings,
    job_provider_cache,
    job_provider_quota
FROM PUBLIC;
REVOKE ALL ON SEQUENCE
    job_discovery_settings_id_seq,
    job_provider_settings_id_seq,
    job_provider_cache_id_seq,
    job_provider_quota_id_seq
FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        EXECUTE 'REVOKE ALL ON TABLE job_discovery_settings, job_provider_settings, job_provider_cache, job_provider_quota FROM anon';
        EXECUTE 'REVOKE ALL ON SEQUENCE job_discovery_settings_id_seq, job_provider_settings_id_seq, job_provider_cache_id_seq, job_provider_quota_id_seq FROM anon';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE job_discovery_settings, job_provider_settings TO authenticated';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE job_discovery_settings_id_seq, job_provider_settings_id_seq TO authenticated';
        EXECUTE 'REVOKE TRUNCATE, REFERENCES, TRIGGER ON TABLE job_discovery_settings, job_provider_settings FROM authenticated';
        EXECUTE 'REVOKE ALL ON TABLE job_provider_cache, job_provider_quota FROM authenticated';
        EXECUTE 'REVOKE TRUNCATE, REFERENCES, TRIGGER ON TABLE job_provider_cache, job_provider_quota FROM authenticated';
        EXECUTE 'REVOKE ALL ON SEQUENCE job_provider_cache_id_seq, job_provider_quota_id_seq FROM authenticated';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
        EXECUTE 'GRANT ALL ON TABLE job_discovery_settings, job_provider_settings, job_provider_cache, job_provider_quota TO service_role';
        EXECUTE 'GRANT ALL ON SEQUENCE job_discovery_settings_id_seq, job_provider_settings_id_seq, job_provider_cache_id_seq, job_provider_quota_id_seq TO service_role';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'careerpilot_app') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE job_discovery_settings, job_provider_settings, job_provider_cache, job_provider_quota TO careerpilot_app';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE job_discovery_settings_id_seq, job_provider_settings_id_seq, job_provider_cache_id_seq, job_provider_quota_id_seq TO careerpilot_app';
    END IF;
END $$;
