-- CareerPilot per-user scoping.
-- Apply once in the Supabase SQL editor (project kcrtedhezyovfygfotia).
-- Existing rows are sample data and are deleted. Running this script again
-- drops career_profiles, cv_documents, cv_versions, and job_listings.

DROP TABLE IF EXISTS cv_versions;
DROP TABLE IF EXISTS job_listings;
DROP TABLE IF EXISTS cv_documents;
DROP TABLE IF EXISTS career_profiles;

CREATE TABLE career_profiles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL UNIQUE,
    full_name character varying(160) NOT NULL DEFAULT '',
    email character varying(320) NOT NULL DEFAULT '',
    headline character varying(200) NOT NULL DEFAULT '',
    location character varying(200) NOT NULL DEFAULT 'New Zealand',
    summary text NOT NULL DEFAULT '',
    skills text NOT NULL DEFAULT ''
);

CREATE TABLE cv_documents (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL UNIQUE,
    name character varying(160) NOT NULL DEFAULT '',
    headline character varying(200) NOT NULL DEFAULT '',
    summary text NOT NULL DEFAULT '',
    experience text NOT NULL DEFAULT '',
    skills text NOT NULL DEFAULT '',
    education text NOT NULL DEFAULT ''
);

CREATE TABLE cv_versions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL,
    label character varying(160) NOT NULL,
    job_title character varying(200) NOT NULL DEFAULT '',
    company character varying(200) NOT NULL DEFAULT '',
    notes text NOT NULL DEFAULT '',
    snapshot json NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX cv_versions_user_id_idx ON cv_versions (user_id);

CREATE TABLE job_listings (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL,
    title character varying(200) NOT NULL,
    company character varying(200) NOT NULL DEFAULT '',
    location character varying(200) NOT NULL DEFAULT 'New Zealand',
    description text NOT NULL DEFAULT '',
    url character varying(2000) NOT NULL DEFAULT '',
    source character varying(120) NOT NULL DEFAULT 'Manually added',
    status character varying(20) NOT NULL DEFAULT 'saved',
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX job_listings_user_id_idx ON job_listings (user_id);
CREATE INDEX job_listings_status_idx ON job_listings (status);
CREATE UNIQUE INDEX job_listings_user_url_unique ON job_listings (user_id, url) WHERE url <> '';

ALTER TABLE career_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE cv_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE cv_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE job_listings ENABLE ROW LEVEL SECURITY;

-- Owner policies for the authenticated role (Supabase Data API).
-- auth.uid() is wrapped in a scalar subquery so Postgres can cache it per statement.
-- The backend role careerpilot_app has BYPASSRLS and keeps a permissive policy,
-- so these policies do not constrain the API. The API must filter by user_id itself.
DO $$
BEGIN
    IF to_regprocedure('auth.uid()') IS NOT NULL
       AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        CREATE POLICY career_profiles_owner ON career_profiles
            FOR ALL TO authenticated
            USING ((SELECT auth.uid()) = user_id)
            WITH CHECK ((SELECT auth.uid()) = user_id);
        CREATE POLICY cv_documents_owner ON cv_documents
            FOR ALL TO authenticated
            USING ((SELECT auth.uid()) = user_id)
            WITH CHECK ((SELECT auth.uid()) = user_id);
        CREATE POLICY cv_versions_owner ON cv_versions
            FOR ALL TO authenticated
            USING ((SELECT auth.uid()) = user_id)
            WITH CHECK ((SELECT auth.uid()) = user_id);
        CREATE POLICY job_listings_owner ON job_listings
            FOR ALL TO authenticated
            USING ((SELECT auth.uid()) = user_id)
            WITH CHECK ((SELECT auth.uid()) = user_id);
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'careerpilot_app') THEN
        CREATE POLICY careerpilot_app_all ON career_profiles
            FOR ALL TO careerpilot_app USING (true) WITH CHECK (true);
        CREATE POLICY careerpilot_app_all ON cv_documents
            FOR ALL TO careerpilot_app USING (true) WITH CHECK (true);
        CREATE POLICY careerpilot_app_all ON cv_versions
            FOR ALL TO careerpilot_app USING (true) WITH CHECK (true);
        CREATE POLICY careerpilot_app_all ON job_listings
            FOR ALL TO careerpilot_app USING (true) WITH CHECK (true);
    END IF;
END $$;

REVOKE ALL ON TABLE career_profiles, cv_documents, cv_versions, job_listings FROM PUBLIC;
REVOKE ALL ON SEQUENCE
    career_profiles_id_seq,
    cv_documents_id_seq,
    cv_versions_id_seq,
    job_listings_id_seq
FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        EXECUTE 'REVOKE ALL ON TABLE career_profiles, cv_documents, cv_versions, job_listings FROM anon';
        EXECUTE 'REVOKE ALL ON SEQUENCE career_profiles_id_seq, cv_documents_id_seq, cv_versions_id_seq, job_listings_id_seq FROM anon';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE career_profiles, cv_documents, cv_versions, job_listings TO authenticated';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE career_profiles_id_seq, cv_documents_id_seq, cv_versions_id_seq, job_listings_id_seq TO authenticated';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
        EXECUTE 'GRANT ALL ON TABLE career_profiles, cv_documents, cv_versions, job_listings TO service_role';
        EXECUTE 'GRANT ALL ON SEQUENCE career_profiles_id_seq, cv_documents_id_seq, cv_versions_id_seq, job_listings_id_seq TO service_role';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'careerpilot_app') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE career_profiles, cv_documents, cv_versions, job_listings TO careerpilot_app';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE career_profiles_id_seq, cv_documents_id_seq, cv_versions_id_seq, job_listings_id_seq TO careerpilot_app';
    END IF;
END $$;
